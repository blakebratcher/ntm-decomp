#!/usr/bin/env python3
"""Generate typed region sources from config/regions/<cpu>/*.tsv.

Each row classifies one byte range that is not instruction code:

    <hex start>  <hex size>  <kind>  <name>  <evidence>

kind is one of
  fill:XX   a constant byte run (XX hex). Emitted as dcb.b straight from the
            table, so it needs no ROM input at all.
  data      a consumer-evidenced table/asset whose bytes come from the owner's
            ROM at build time (asset extraction, like the C/S/V ROMs). The
            evidence must name the instruction or table that reads it.
  unref     bytes with a validated record format but NO known consumer yet.
            Built like data, reported separately: an open item, not a proof.

Outputs land in build/gen/<cpu>/regions/ (ignored) and are assembled by the
builders with the rest of the corpus; the byte gate verifies them. Rows must
not overlap one another and must carry an evidence note. Unknown bytes stay
unknown: a row is a claim about what the bytes are, backed by its evidence.
"""
import argparse
import pathlib
import re

REPO = pathlib.Path(__file__).resolve().parent.parent
WORK = REPO / 'build' / 'work'
CPUS = {
    # cpu: (windows, org line, byte directive, byte format, fill directive)
    'p1': ([(0, 0x100000), (0x200000, 0x300000)], ' org ${:x}', 'dc.b', '${:02x}',
           'dcb.b {n},${v:02x}'),
    'm1': ([(0, 0x20000)], ' .org 0x{:x}', '.byte', '0x{:02x}', '.space {n},0x{v:02x}'),
}
NAME = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*$')


def load(cpu, root=REPO):
    windows = CPUS[cpu][0]
    rows = []
    for table in sorted((root / 'config' / 'regions' / cpu).glob('*.tsv')):
        for n, line in enumerate(table.read_text().splitlines(), 1):
            if not line.strip() or line.startswith('#'):
                continue
            where = f'{table.name}:{n}'
            fields = line.split('\t')
            if len(fields) < 5 or not fields[4].strip():
                raise ValueError(f'{where}: need start, size, kind, name, evidence')
            start, size = int(fields[0], 16), int(fields[1], 16)
            kind, name = fields[2], fields[3]
            if size <= 0 or not any(lo <= start and start + size <= hi for lo, hi in windows):
                raise ValueError(f'{where}: [{start:#x}, +{size:#x}) empty or outside one window')
            if not NAME.match(name):
                raise ValueError(f'{where}: bad name {name!r}')
            if kind.startswith('fill:'):
                value = int(kind[5:], 16)
                if not 0 <= value <= 0xff:
                    raise ValueError(f'{where}: fill byte out of range')
            elif kind not in ('data', 'unref', 'dead'):
                raise ValueError(f'{where}: unknown kind {kind!r}')
            rows.append({'start': start, 'size': size, 'kind': kind, 'name': name,
                         'evidence': fields[4].strip(), 'where': where})
    rows.sort(key=lambda r: r['start'])
    for a, b in zip(rows, rows[1:]):
        if b['start'] < a['start'] + a['size']:
            raise ValueError(f"{b['where']}: overlaps {a['where']}")
    names = [r['name'] for r in rows]
    dup = {x for x in names if names.count(x) > 1}
    if dup:
        raise ValueError(f'duplicate region names: {sorted(dup)}')
    return rows


def rom_reader(cpu, work=WORK):
    if cpu == 'p1':
        blobs = {0: work / 'p1.fixed.cpu.bin', 0x200000: work / 'p1.bank.cpu.bin'}
    else:
        blobs = {0: work / 'p1.m1.pristine.bin'}
    cache = {}

    def read(start, size):
        base = max(b for b in blobs if b <= start)
        if base not in cache:
            cache[base] = blobs[base].read_bytes()
        return cache[base][start - base:start - base + size]
    return read


def render(cpu, row, read=None):
    _, org, byte_dir, byte_fmt, fill_dir = CPUS[cpu]
    head = (f'; generated by tools/gen_regions.py from {row["where"]} - do not edit\n'
            f'; kind: {row["kind"]}\n; evidence: {row["evidence"]}\n'
            f'{org.format(row["start"])}\n{row["name"]}:\n')
    if row['kind'].startswith('fill:'):
        return head + f' {fill_dir.format(n=row["size"], v=int(row["kind"][5:], 16))}\n'
    blob = read(row['start'], row['size'])
    if len(blob) != row['size']:
        raise ValueError(f'{row["where"]}: ROM image too short')
    lines = [f' {byte_dir} ' + ','.join(byte_fmt.format(b) for b in blob[i:i + 16])
             for i in range(0, len(blob), 16)]
    return head + '\n'.join(lines) + '\n'


def generate(cpu, out_dir, root=REPO, work=WORK):
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob('*.s'):
        stale.unlink()
    read = rom_reader(cpu, work)
    rows = load(cpu, root)
    for row in rows:
        (out_dir / f'{row["start"]:08x}_{row["name"]}.s').write_text(render(cpu, row, read))
    return rows


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('cpu', choices=sorted(CPUS))
    args = ap.parse_args()
    rows = generate(args.cpu, REPO / 'build' / 'gen' / args.cpu / 'regions')
    kinds = {}
    for r in rows:
        k = 'fill' if r['kind'].startswith('fill:') else r['kind']
        kinds[k] = kinds.get(k, 0) + r['size']
    print(f'{args.cpu}: {len(rows)} regions ' +
          ', '.join(f'{k} {v:,} bytes' for k, v in sorted(kinds.items())))


if __name__ == '__main__':
    main()
